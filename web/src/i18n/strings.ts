export const STRINGS: Record<Lang, Strings> = { en, fa };

export function fmtMeters(m: number, t: Strings, lang: Lang): string {
  const nf = new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { maximumFractionDigits: m >= 1000 ? 2 : 0 });
  return m >= 1000 ? `${nf.format(m / 1000)} ${t.km}` : `${nf.format(Math.round(m))} ${t.m}`;
}

export function fmtNum(n: number, lang: Lang, digits = 0): string {
  return new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { maximumFractionDigits: digits }).format(n);
}
